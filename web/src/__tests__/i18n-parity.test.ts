describe('i18n parity', () => {
  it('has one messages file for each language of the switch and no orphan file', () => {
    expect(
      readdirSync(MESSAGES_DIR)
        .map((file) => file.replace('.json', ''))
        .sort(),
    ).toEqual([...LOCALES].sort());
  });

  it.each([...LOCALES])('has the same keys in %s and en', (locale) => {
    expect(flatten(load(locale)).sort()).toEqual(flatten(BASE).sort());
  });

  it.each([...LOCALES])('contains the required keys in %s', (locale) => {
    const keys = flatten(load(locale));
    for (const key of REQUIRED) expect(keys).toContain(key);
  });

  it.each([...LOCALES])('has no empty messages and no em dash in %s', (locale) => {
    const raw = JSON.stringify(load(locale));
    expect(raw.includes(String.fromCharCode(0x2014))).toBe(false);
    expect(raw.includes('""')).toBe(false);
  });
});
